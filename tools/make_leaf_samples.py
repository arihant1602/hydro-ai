"""Bundle sample leaves into the app to demonstrate the leaf disease model (Leaf check -> Try a sample).

Picks 2 images per class at random (seeded, not cherry-picked) from the held-out TEST split of
tools/train_leaf_model.py, so the model never saw them in training, and embeds them as base64 in
mobile/src/data/leaf_samples.ts.

Images: PlantVillage (Hughes & Salathe 2015), CC BY-SA 3.0, https://github.com/spMohanty/PlantVillage-Dataset

    .venv/bin/python tools/make_leaf_samples.py
"""
import base64
import json
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "raw" / "plantvillage_maize"
OUT = ROOT / "mobile" / "src" / "data" / "leaf_samples.ts"
FOLDER = {
    "healthy": "healthy",
    "Common_rust": "common_rust",
    "Northern_Leaf_Blight": "northern_leaf_blight",
    "Cercospora_leaf_spot_Gray_leaf_spot": "gray_leaf_spot",
}
PER_CLASS = 2
SEED = 7


def main():
    test = json.loads((DATA / "split.json").read_text())["test"]
    rng = np.random.default_rng(SEED)
    samples = []
    for folder, cls in FOLDER.items():
        files = sorted(f for f in test if Path(f).parent.name == folder)
        for f in rng.choice(files, size=PER_CLASS, replace=False):
            raw = Path(f).read_bytes()
            w, h = Image.open(f).size
            samples.append({"id": f"{cls}_{len(samples)}", "truth": cls, "source": Path(f).name, "width": w, "height": h,
                            "jpeg": base64.b64encode(raw).decode()})
    body = ",\n".join(
        f"  {{ id: {json.dumps(s['id'])}, truth: {json.dumps(s['truth'])}, source: {json.dumps(s['source'])}, "
        f"width: {s['width']}, height: {s['height']},\n    jpeg: {json.dumps(s['jpeg'])} }}"
        for s in samples)
    OUT.write_text(f"""// Generated by tools/make_leaf_samples.py: do not edit.
// Sample maize leaves for demonstrating the leaf disease model, drawn at random from the model's held-out test
// images (never used in training). Images: PlantVillage (Hughes & Salathe 2015), CC BY-SA 3.0,
// https://github.com/spMohanty/PlantVillage-Dataset

export interface LeafSample {{
  id: string;
  /** The dataset's label: healthy, common_rust, northern_leaf_blight or gray_leaf_spot. */
  truth: string;
  source: string;
  width: number;
  height: number;
  /** JPEG, base64. */
  jpeg: string;
}}

export const SAMPLE_CREDIT = 'Sample leaves: PlantVillage (Hughes & Salathé 2015), CC BY-SA 3.0';

export const LEAF_SAMPLES: LeafSample[] = [
{body},
];
""")
    print(f"{len(samples)} samples, {OUT.stat().st_size / 1024:.0f} KB -> {OUT}")
    for s in samples:
        print(" ", s["truth"], s["source"])


if __name__ == "__main__":
    main()
